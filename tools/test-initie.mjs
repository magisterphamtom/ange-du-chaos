import assert from "node:assert/strict";
import { actionInitie, connaitZen, bonusFrappeNexus, toursHandicapApresZen, handicapContreZen, issueDevier } from "../module/initie-regles.mjs";
assert.equal(actionInitie("Zen de l’Initié"), "zen");
assert.equal(actionInitie("Initié : Zen de l’initié"), "zen");
assert.equal(actionInitie("Cri de l’Initié"), "cri");
assert.equal(actionInitie("Talent d’Initié : Le Cri"), "cri");
assert.equal(actionInitie("Dévier le vent, étreindre le vide"), "devier");
assert.equal(actionInitie("L’Armure de l’Initié"), "armure");
assert.equal(actionInitie("Transe curative de l’Initié"), "transe");
for (const n of ["Mon corps est une arme", "Œil de faucon", "Armure du Chaos", "Frénésie du Chaos", "Fourberie du Chaos"]) assert.equal(actionInitie(n), null, n);
assert.ok(connaitZen(["Sang fendyr", "Zen de l’Initié"])); assert.ok(!connaitZen(["Sang fendyr"]));
assert.equal(bonusFrappeNexus(["Rilji’nn", "Rhys"], 6), 6);
assert.equal(bonusFrappeNexus(["Rilji’nn"], 6), 0);
assert.equal(toursHandicapApresZen(5), 3); assert.equal(toursHandicapApresZen(0), 0);
assert.ok(handicapContreZen({ adversaireEnZen: true, moiConnaitZen: false }));
assert.ok(!handicapContreZen({ adversaireEnZen: true, moiConnaitZen: true }));
assert.ok(!handicapContreZen({ adversaireEnZen: false, moiConnaitZen: false }));
assert.match(issueDevier(true, "majeure"), /désarme/); assert.match(issueDevier(false, "critique"), /retourne/);
console.log("test-initie : OK");
